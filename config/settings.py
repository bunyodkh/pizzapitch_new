# when a new application comes in.
#
# TELEGRAM_BOT_TOKEN: the bot's own token from @BotFather, e.g.
#   "123456789:AAExampleTokenString". This authenticates as the bot — it is
#   the same value regardless of which chat you send to, it is NOT a
#   per-group token (Telegram groups don't have tokens of their own).
#
# TELEGRAM_GROUP_CHAT_ID: the numeric ID of the target GROUP chat the bot
#   should post into. The bot must first be added as a member of that group.
#   Group/supergroup IDs are negative (supergroups start with "-100", e.g.
#   -1001234567890) — a positive ID is a private one-on-one chat, not a group.
#   To find it: add the bot to the group, send any message in the group,
#   then open https://api.telegram.org/bot<TOKEN>/getUpdates in a browser
#   and read the "chat": {"id": ...} value for that group message.
#
# Both values live in .env (gitignored) — see .env.example for the template.
